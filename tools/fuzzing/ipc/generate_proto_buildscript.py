import os
from glob import glob
from argparse import ArgumentParser


def parse_args():
    parser = ArgumentParser(description='Generate C++ mutator factory from proto files')
    parser.add_argument('-d', '--dir', type=str, required=True)
    parser.add_argument('-o', '--output-file', type=str, default='moz.build')
    return parser.parse_args()



def gen_moz_build(outfile, cpps, headers, protos):
    with open(outfile, 'w') as f:
        f.write("""# -*- Mode: python; c-basic-offset: 4; indent-tabs-mode: nil; tab-width: 40 -*-
# vim: set filetype=python:
# This Source Code Form is subject to the terms of the Mozilla Public
# License, v. 2.0. If a copy of the MPL was not distributed with this
# file, You can obtain one at http://mozilla.org/MPL/2.0/.


# AUTO-GENERATED - DO NOT EDIT !!!!!!!!!!

Library("fuzzer-ipc-protocol-protobuf")

SOURCES += [""")
        for cpp in cpps:
            f.write("""
    "%s",""" % cpp)
        f.write("""
]

EXPORTS.mozilla.fuzzing.protobuf += [""")
        for header in headers:
            f.write("""
    "%s",""" % header)
        f.write("""
]

FINAL_LIBRARY = "xul"

""")

def main():
    # parse arguments
    args = parse_args()
    print(args.dir)
    # check paths
    if not os.path.exists(args.dir):
        print(f"Input directory '{args.dir}' doesn't exist")
        return
    if not os.path.exists(args.output_file):
        os.makedirs(args.output_file)

    # find .ph.h and .pb.cc files in input dir
    cpps_paths = glob(os.path.join(args.dir, "**/*.pb.cc"), recursive=True)
    headers_paths = glob(os.path.join(args.dir, "**/*.pb.h"), recursive=True)
    all_proto_paths = glob(os.path.join(args.dir, "**/*.proto"), recursive=True)
    proto_h_paths = glob(os.path.join(args.dir, "**/*.h.proto"), recursive=True)

    # here we need to convert each "real" .proto file (not a header) into a ...Protobuf.cpp file
    # which will be included as a "UNIFIED_SOURCE"
    # These ...Protobuf.cpp files are generated by ipdl.py and need to be included somewhere in order to be recognized by the moz build backend
    proto_paths = list(set(all_proto_paths) - set(proto_h_paths))

    protobuf_paths = []
    for proto in proto_paths:
        protobuf_paths.append(os.path.splitext(os.path.basename(proto))[0] + "Protobuf.cpp")

    cpps = sorted([os.path.basename(p) for p in cpps_paths], key=str.lower)
    headers = sorted([os.path.basename(p) for p in headers_paths], key=str.lower)
    protos = sorted([os.path.basename(p) for p in protobuf_paths], key=str.lower)


    if not cpps:
        print(f"No source files found in input directory")
        return

    outfile = os.path.join(args.dir, args.output_file)

    # parse all protocol + message names
    gen_moz_build(outfile, cpps, headers, protos)

    print("\nDone!")
    print(f"Generated: {outfile}")
    print(f"Added {len(cpps)} source files and {len(headers)} header files")

if __name__ == "__main__":
    main()
